"""Role B (Modeling): the candidate comparison table of ``docs/results.md`` (issue #28).

Run it after ``train``, ``register``, ``promote``, and ``evaluate-test`` on the real splits::

    uv run python -m claimfreq.results > docs/results.md

It reads the tracking server at ``MLFLOW_TRACKING_URI`` and prints Markdown:

- one row per candidate of the latest ``FINISHED`` train run (the candidate set ``register``
  uses), with its ``val_*`` metrics, whether it beats the constant baseline on the selection
  metric (``is_better``, the rule ``register`` applies), and which candidate is the best;
- the champion's ``test_*`` metrics, logged by ``evaluate-test``.

This is a reporting helper, not a ``claimfreq`` command: nothing in the pipeline calls it.
"""

from __future__ import annotations

import math

import mlflow
from mlflow.entities import Run
from mlflow.tracking import MlflowClient

from claimfreq.contracts import env
from claimfreq.contracts.model import (
    MLFLOW_EXPERIMENT_NAME,
    REGISTERED_MODEL_NAME,
    TAG_ALGORITHM,
    TAG_DATA_HASH,
    TAG_SEMVER,
    MetricName,
    MetricPrefix,
    is_better,
)
from claimfreq.contracts.params import Params, load_params
from claimfreq.registry import (
    current_champion,
    finished_children,
    latest_finished_parent,
    select_best,
)
from claimfreq.training import ALGORITHM_CONSTANT

METRIC_ORDER = (MetricName.POISSON_DEVIANCE, MetricName.GINI, MetricName.CALIBRATION_RATIO)
# Marks in the "beats constant" column.
BEATS = "yes"
DOES_NOT_BEAT = "**no**"


def _value(run: Run, prefix: MetricPrefix, name: str) -> str:
    value = run.data.metrics.get(f"{prefix}{name}")
    return "n/a" if value is None or math.isnan(value) else f"{value:.4f}"


def _row(cells: list[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def candidate_table(children: list[Run], selection_metric: str) -> list[str]:
    """Return the Markdown table of the candidates' ``val_*`` metrics against the baseline."""
    key = f"{MetricPrefix.VAL}{selection_metric}"
    constant = next(
        (run for run in children if run.data.tags.get(TAG_ALGORITHM) == ALGORITHM_CONSTANT), None
    )
    best = select_best(children, selection_metric)
    lines = [
        _row(
            [
                "candidate",
                *(f"`{MetricPrefix.VAL}{name}`" for name in METRIC_ORDER),
                f"beats constant on `{key}`",
            ]
        ),
        _row(["---"] + ["---:"] * len(METRIC_ORDER) + [":---:"]),
    ]
    for run in children:
        algorithm = run.data.tags.get(TAG_ALGORITHM, run.info.run_name)
        if run.info.run_id == best.info.run_id:
            algorithm = f"**{algorithm}** (best)"
        if constant is None or run.info.run_id == constant.info.run_id:
            beats = "baseline" if constant is not None else "n/a"
        else:
            value = run.data.metrics.get(key, math.nan)
            beats = (
                BEATS
                if is_better(selection_metric, value, constant.data.metrics[key])
                else (DOES_NOT_BEAT)
            )
        metric_cells = [_value(run, MetricPrefix.VAL, name) for name in METRIC_ORDER]
        lines.append(_row([algorithm, *metric_cells, beats]))
    return lines


def render(params: Params | None = None) -> str:
    """Return the Markdown report of the latest candidate set and the champion."""
    params = params or load_params()
    selection_metric = params.training.selection_metric
    mlflow.set_tracking_uri(env.get(env.MLFLOW_TRACKING_URI))
    client = MlflowClient()
    experiment = client.get_experiment_by_name(MLFLOW_EXPERIMENT_NAME)
    if experiment is None:
        raise SystemExit(f"no experiment {MLFLOW_EXPERIMENT_NAME!r}; run `claimfreq train` first")
    parent, _ = latest_finished_parent(client, experiment.experiment_id)
    children = finished_children(client, experiment.experiment_id, parent.info.run_id)

    lines = [
        "# Results",
        "",
        "Generated by `uv run python -m claimfreq.results`; do not edit by hand.",
        "",
        "## Candidates on the validation split",
        "",
        f"Candidate set `{parent.info.run_id}`, train split md5 "
        f"`{parent.data.tags.get(TAG_DATA_HASH, 'unknown')}`. Selection metric: "
        f"`{MetricPrefix.VAL}{selection_metric}`. A **no** flags a candidate that does not "
        "beat the constant baseline.",
        "",
        *candidate_table(children, selection_metric),
        "",
        "## Champion on the test split",
        "",
    ]
    champion = current_champion(client)
    if champion is None:
        lines.append("No champion yet: run `claimfreq promote --version N`.")
    else:
        run = client.get_run(champion.run_id)
        algorithm = run.data.tags.get(TAG_ALGORITHM, "unknown")
        lines.append(
            f"`{REGISTERED_MODEL_NAME}` version {champion.version} "
            f"({champion.tags.get(TAG_SEMVER, 'no semver')}, {algorithm})."
        )
        lines.append("")
        if not any(key.startswith(MetricPrefix.TEST) for key in run.data.metrics):
            lines.append("Not evaluated yet: run `claimfreq evaluate-test`.")
        else:
            lines.append(_row(["split", *(f"`{name}`" for name in METRIC_ORDER)]))
            lines.append(_row(["---"] + ["---:"] * len(METRIC_ORDER)))
            for prefix in (MetricPrefix.VAL, MetricPrefix.TEST):
                split = prefix.removesuffix("_")
                lines.append(_row([split, *(_value(run, prefix, n) for n in METRIC_ORDER)]))
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    print(render(), end="")
